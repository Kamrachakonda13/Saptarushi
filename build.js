/* =========================================================
   STOTRA NIDHI integration
   Lyrics for ~25 well-known stotras, pulled from
   stotranidhi.com, become Books (long-form Telugu) and
   Audio tiles (recording served from their channel).
   ========================================================= */
const STOTRAS = JSON.parse(fs.readFileSync(path.join(ROOT, 'stotras.json'), 'utf8')).items;
const snAudio = [];
const snBooks = [];
STOTRAS.forEach((s) => {
  const slug = 'sn-' + s.slug;
  const title = s.en || s.te;
  const a = {
    slug, deity: s.deity, te: s.te, en: title, duration: '—', tag: 'Stotra',
    localPath: '', src: s.src, text: 'Telugu text and chant from Stotra Nidhi (stotranidhi.com) — the full lyrics are in the Books section.',
  };
  snAudio.push(a);
  D.audio.push(a);
  const paras = s.paras.filter(Boolean);
  const chapters = [];
  if (paras.length <= 32) { chapters.push({ title: 'పారాయణ పాఠం', paras }); }
  else {
    for (let i = 0; i < paras.length; i += 32) {
      chapters.push({ title: 'భాగం – ' + (chapters.length + 1), paras: paras.slice(i, i + 32) });
    }
  }
  const b = {
    slug, deity: s.deity, te: s.te, en: title, meta: 'Stotra Nidhi · పారాయణ పాఠం · శ్లో. తా.',
    chapters, source: s.src,
  };
  snBooks.push(b);
  D.books.push(b);
  BOOK_PAGES[slug] = s.te;
});
