/* ---------- Temples helpers ---------- */
function templeBadge(t) { return TEMPLE_CATS[t.category] || t.category; }

const DEITY_EXT = { krishna: '.png' };
function deityImgAsset(slug, depth) {
  const f = 'assets/deities/' + slug + (DEITY_EXT[slug] || '.jpg');
  return fs.existsSync(path.join(ROOT, f)) ? rel(depth, f) : '';
}
function templeCardImg(cat, id) {
  const base = 'assets/temples/' + cat + '/' + id + '-';
  if (fs.existsSync(path.join(ROOT, base + 'temple.jpg'))) return base + 'temple.jpg';
  if (fs.existsSync(path.join(ROOT, base + 'deity.jpg'))) return base + 'deity.jpg';
  return '';
}
function templeCardImgRel(cat, id, depth) {
  const u = templeCardImg(cat, id);
  return u ? rel(depth, u) : '';
}

function templeJs(t) {
  return {
    id: t.id, category: t.category, categoryLabel: templeBadge(t), name: t.name, temple: t.temple,
    deity: t.deity, city: t.city, state: t.state, location: t.location, story: t.story,
    significance: t.significance, bodyPart: t.bodyPart || '', element: t.element || '',
    coords: t.coordinates,
    cardImg: templeCardImg(t.category, t.id),
  };
}
function templeCard(rootDepth, t, mode) {
  const img = templeCardImgRel(t.category, t.id, rootDepth);
  const imgHtml = img ? `<img class="temple-img" src="${img}" alt="${esc(t.name)}" loading="lazy"/>` : '';
  const content = `
    ${imgHtml}
    <div class="temple-content">
      <span class="temple-badge">${esc(templeBadge(t))}</span>
      <h2 class="temple-name">${esc(t.name)}</h2>
      <div class="temple-deity">${esc(t.deity)}</div>
      <div class="temple-loc">${esc(t.location)}</div>
      <div class="temple-read"></div>
    </div>`;
  if (mode === 'button') {
    return `<article class="temple-card">${content.replace('<div class="temple-read"></div>',
      '<div class="temple-read"><button type="button" onclick="openTemple(\'' + t.id + '\')">Explore Temple</button></div>')}</article>`;
  }
  return `<article class="temple-card">${content.replace('<div class="temple-read"></div>',
    '<div class="temple-read"><a href="' + rel(rootDepth, 'temples/' + t.id + '.html') + '" class="temple-link-btn">Explore Temple</a></div>')}</article>`;
}

